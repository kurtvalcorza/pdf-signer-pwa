import { PDFArray, PDFDict, PDFDocument, PDFName, PDFNumber } from 'pdf-lib';

const CERTIFIED_NO_CHANGES =
  'This PDF is certified with a “no changes allowed” policy. Adding any signature would break ' +
  'that certification, so it cannot be signed here.';
const CERTIFIED =
  'This PDF is certified. Its policy does not allow a new signature field to be added, and this ' +
  'app signs by adding one, so it cannot be signed here without breaking the certification.';
const FIELD_LOCKED =
  'An existing signature on this PDF locks its form fields (FieldMDP). Adding a signature field ' +
  'could break that signature, so it cannot be signed here.';
const UNKNOWN_POLICY =
  'An existing signature on this PDF uses a modification policy this app does not recognise, so ' +
  'it cannot be signed here.';

/**
 * A human-readable reason why appending a signature to this PDF would not be a permitted
 * modification, else null. Fails closed on anything it cannot classify.
 *
 * The app's only way to counter-sign is to APPEND A NEW signature field. That is what decides the
 * certified cases: pyHanko reports a new field after a certification signature as a disallowed
 * change at every /P, including 2 and 3 (tests/signing/policy.test.ts, fixtures generated by
 * pyHanko). Those levels permit signing an EXISTING empty field, a path this app does not have, so
 * every certified document is refused. Approval signatures, which the gate confirms, are allowed.
 */
export function signingPolicyBlock(doc: PDFDocument): string | null {
  const perms = doc.catalog.lookupMaybe(PDFName.of('Perms'), PDFDict);
  let certified = !!perms?.has(PDFName.of('DocMDP'));

  for (const sig of allSignatureDicts(doc)) {
    const refs = sig.lookupMaybe(PDFName.of('Reference'), PDFArray);
    for (let i = 0; refs && i < refs.size(); i++) {
      const sigRef = refs.lookupMaybe(i, PDFDict);
      const method = sigRef?.lookupMaybe(PDFName.of('TransformMethod'), PDFName);
      if (method === PDFName.of('FieldMDP')) return FIELD_LOCKED;
      if (method === PDFName.of('DocMDP')) {
        const params = sigRef!.lookupMaybe(PDFName.of('TransformParams'), PDFDict);
        if (params?.lookupMaybe(PDFName.of('P'), PDFNumber)?.asNumber() === 1) {
          return CERTIFIED_NO_CHANGES;
        }
        certified = true;
      } else if (method !== PDFName.of('Identity')) {
        return UNKNOWN_POLICY;
      }
    }
  }
  return certified ? CERTIFIED : null;
}

/** The certification signature (catalog /Perms /DocMDP) plus every signed field's /V. */
function* allSignatureDicts(doc: PDFDocument): Generator<PDFDict> {
  const perms = doc.catalog.lookupMaybe(PDFName.of('Perms'), PDFDict);
  const certSig = perms?.lookupMaybe(PDFName.of('DocMDP'), PDFDict);
  if (certSig) yield certSig;

  const acro = doc.catalog.lookupMaybe(PDFName.of('AcroForm'), PDFDict);
  const fields = acro?.lookupMaybe(PDFName.of('Fields'), PDFArray);
  if (!fields) return;
  const stack: PDFDict[] = [];
  const seen = new Set<PDFDict>();
  const push = (arr: PDFArray) => {
    for (let i = 0; i < arr.size(); i++) {
      const d = arr.lookupMaybe(i, PDFDict);
      if (d) stack.push(d);
    }
  };
  push(fields);
  while (stack.length) {
    const field = stack.pop()!;
    if (seen.has(field)) continue; // cyclic /Parent–/Kids guard
    seen.add(field);
    const value = field.lookupMaybe(PDFName.of('V'), PDFDict);
    if (value?.lookupMaybe(PDFName.of('ByteRange'), PDFArray)) yield value;
    const kids = field.lookupMaybe(PDFName.of('Kids'), PDFArray);
    if (kids) push(kids);
  }
}
